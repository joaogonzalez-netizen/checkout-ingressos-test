export function isSupabase(url: string) {
  try {
    return new URL(url).hostname.endsWith(".supabase.com") || new URL(url).hostname.endsWith(".supabase.co");
  } catch {
    return false;
  }
}

/** PoolConfig para o PrismaPg. No Supabase: TLS verificado com a CA oficial e sem parâmetros de URL que o driver não entende (pgbouncer, supa). */
export function pgPoolConfig(url: string, max?: number): PoolConfig {
  if (!isSupabase(url)) return { connectionString: url, max };
  const u = new URL(url);
  u.search = "";
  return { connectionString: u.toString(), max, ssl: { ca: SUPABASE_ROOT_CA, rejectUnauthorized: true } };
}
